'use strict';
const assert=require('node:assert/strict'),v=require('./personal_timer_focus_v77.js');
const now=10_000_000,h=3600000;
const running={id:'a',name:'Studying',status:'running',segments:[{start:now-h,end:null}]};
const paused={id:'b',name:'Gym',status:'paused',segments:[{start:now-2*h,end:now-h}]};
const finished={id:'c',name:'Done',status:'finished',segments:[{start:now-3*h,end:now-h}]};
assert.equal(v.choose([running,paused,finished]).id,'a');
assert.equal(v.choose([paused,finished]).id,'b');
assert.equal(v.choose([running,paused], 'b').id,'b');
assert.equal(v.choose([finished]),null);
assert.equal(v.choose([]),null);
assert.equal(v.duration(running,now),h);
assert.equal(v.duration(running,now+2*h),3*h);
assert.equal(v.duration(paused,now),h);
assert.equal(v.duration(paused,now+2*h),h);
assert.equal(v.duration(finished,now+2*h),2*h);
assert.equal(v.clock(0),'00:00:00');
assert.equal(v.clock(h+65000),'01:01:05');
assert.equal(v.clock(24*h+1000),'24:00:01');
assert.equal(v.clock(-1000),'00:00:00');
assert.equal(v.duration({status:'running',segments:[{start:now+10,end:null}]},now),0);
assert.equal(v.duration(null,now),0);
console.log('V77 timer focus: 16/16 pure duration and selection assertions passed');
