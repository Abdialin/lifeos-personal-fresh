const assert=require('node:assert/strict'),fs=require('node:fs');
const api=require('./personal_plan_evidence_v250.js');
const at=Date.UTC(2026,10,19,18,0),H=3600000;
const plan={id:'p1',name:'Focused studying',startAt:at-6*H,endAt:at-5*H,status:'planned',sessionId:null};
const finished={id:'s1',name:'Focused studying',status:'finished',startAt:at-6*H+10*60000,endAt:at-5*H+2*60000,segments:[]};
const workspace={version:1,schedule:[plan],sessions:[finished],goals:[]};
const matches=api.suggestions(workspace,at);
assert.equal(matches.length,1);
assert.equal(matches[0].planId,'p1');
assert.equal(matches[0].sessionId,'s1');
assert.equal(plan.sessionId,null,'Read-only suggestion never modifies plan');
assert.equal(api.suggestions({...workspace,schedule:[{...plan,sessionId:'s1'}]},at).length,0);
assert.equal(api.suggestions({...workspace,sessions:[finished,{...finished,id:'s2'}]},at).length,0,'Two candidate sessions must be ambiguous');
assert.equal(api.suggestions({...workspace,sessions:[{...finished,name:'Gym'}]},at).length,0);
assert.equal(api.suggestions({...workspace,sessions:[{...finished,source:'development-starter'}]},at).length,0);
assert.equal(api.suggestions({...workspace,sessions:[{...finished,source:'user-reviewed-gap'}]},at).length,0);
assert.equal(api.suggestions({...workspace,schedule:[plan,{...plan,id:'p2'}]},at).length,0,'Two plans for one finished session ambiguous');
assert.equal(api.suggestions({...workspace,sessions:[{...finished,status:'running'}]},at).length,0,'Ongoing sessions are not evidence of completion');
assert.equal(api.suggestions({...workspace,sessions:[{...finished,plannedId:'other'}]},at).length,0,'Sessions from other plans not eligible');
const html=fs.readFileSync('index.html','utf8'),server=fs.readFileSync('server.py','utf8'),src=fs.readFileSync('personal_plan_evidence_v250.js','utf8');
assert.match(src,/root\.confirm\(/,'Explicit user approval required');
assert.match(src,/lifeos-v250-link-evidence/);
assert.doesNotMatch(src,/atomicCommit\(|requestState\('PUT'|localStorage\.setItem\(/);
assert.match(html,/trackingCommit\(\(\)=>\{/);
const a=html.indexOf("window.addEventListener('lifeos-v250-link-evidence'");
assert.ok(a>0);
assert.match(html.slice(a,a+1900),/api\.suggestions\(data,now\(\),14\)/,'Revalidates candidate at commit');
assert.match(html.slice(a,a+1900),/current\.sessionId=proposed\.sessionId/,'Links existing finished session');
assert.match(html,/personal_plan_evidence_v250\.js\?v=250-followup-2/);
assert.match(src,/personal_activity_intelligence_v251\.js\?v=250-followup-2/,'Classification loader must receive the current version');
assert.match(fs.readFileSync('personal_activity_intelligence_v251.js','utf8'),/personal_activity_review_v252\.js\?v=250-followup-2/,'Review loader must receive the current version');
assert.match(server,/'personal_plan_evidence_v250\.js'/);
console.log('PASS V250 uniquely matched completed sessions, no simulated evidence, transaction and approval guards');
