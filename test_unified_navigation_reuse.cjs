const assert=require('node:assert/strict');
const fs=require('node:fs');
const navApi=require('./personal_unified_navigation.js');
const html=fs.readFileSync('index.html','utf8');
const navTag=html.match(/<nav\b[^>]*id="lifeosNavigation"[^>]*>([\s\S]*?)<\/nav>/);
assert.ok(navTag,'Missing navigation markup');
const ids=[...navTag[1].matchAll(/data-view="([^"]+)"/g)].map(x=>x[1]);
assert.deepEqual(ids,navApi.VIEWS.map(x=>x[0]));
const buttons=ids.map(view=>({dataset:{view},attrs:{},listeners:{},setAttribute(k,v){this.attrs[k]=v},removeAttribute(k){delete this.attrs[k]},addEventListener(k,fn){this.listeners[k]=fn}}));
let appended=0;
const nav={querySelectorAll(){return buttons},appendChild(){appended++}};
const heading={textContent:''};
const panels=Array.from({length:26},()=>({classList:{toggle(){}},setAttribute(){}}));
const doc={body:{dataset:{}},getElementById(id){return id==='lifeosNavigation'?nav:id==='lifeosViewTitle'?heading:null},querySelectorAll(sel){return sel==='section.panel'?panels:[]},createElement(){throw Error('Existing navigation must be reused')}};
const win={location:{hash:'#dashboard',pathname:'/',search:''},history:{replaceState(){}},addEventListener(){},scrollTo(){}};
const result=navApi.init(doc,win);
assert.equal(appended,0,'Must not add a duplicate set of tabs');
assert.equal(result.buttons.length,6);
assert.equal(doc.body.dataset.lifeosView,'dashboard');
buttons.find(b=>b.dataset.view==='schedule').listeners.click();
assert.equal(doc.body.dataset.lifeosView,'schedule');
assert.equal(heading.textContent,'Smart schedule');
console.log('Unified navigation reuse PASS');
