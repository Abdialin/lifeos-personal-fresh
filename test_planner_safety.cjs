const assert=require('node:assert/strict');
const p=require('./personal_predictive_planner.js');
const from=new Date(2026,10,9).getTime(),DAY=86400000;
const routine={id:'study',name:'Study',dayOfWeek:1,start:'09:00',durationMinutes:60};
const historical=Array.from({length:14},(_,i)=>({id:'h'+i,status:'finished',endAt:from-(i+1)*DAY,startAt:from-(i+1)*DAY-60000}));
assert.equal(p.build({from,to:from+7*DAY,routines:[routine],sessions:historical}).confidence,'reviewable');
const stale=historical.map(s=>({...s,endAt:s.endAt-40*DAY}));
assert.equal(p.build({from,to:from+7*DAY,routines:[routine],sessions:stale}).confidence,'insufficient');
const future=historical.map(s=>({...s,endAt:from+30*DAY}));
assert.equal(p.build({from,to:from+7*DAY,routines:[routine],sessions:future}).observedTrackedDays,0);
const dup=historical.map(s=>({...s,startAt:from-DAY-60000,endAt:from-DAY}));
assert.equal(p.build({from,to:from+7*DAY,routines:[routine],sessions:dup}).observedTrackedDays,1);
const invalid=[{status:'finished',endAt:from-DAY},{status:'finished',startAt:from-DAY,endAt:from-DAY},{status:'finished',startAt:from-DAY,endAt:from-DAY-1}];
assert.equal(p.historyEvidence(invalid,from).observedTrackedDays,0,'Invalid or zero-length intervals are not evidence');
const a=p.build({from,to:from+7*DAY,routines:[routine]}).proposals[0];
assert.equal(a.requiresApproval,true);
assert.throws(()=>p.approve(a,[{id:'existing',status:'planned',startAt:a.startAt+1000,endAt:a.endAt}],'new',from),/overlapping/);
const active={id:'live',status:'finished',startAt:a.startAt,endAt:a.endAt};
const blocked=p.build({from,to:from+7*DAY,routines:[routine],sessions:[active]}).proposals[0];
assert.deepEqual(blocked.actualConflicts,['live']);
assert.throws(()=>p.approve(blocked,[],'new',from),/conflicts/);
assert.equal(p.approve(a,[],'new',from).reminder,false);
assert.throws(()=>p.build({from,to:from+15*DAY}),/14 days/);
console.log('Planner safety checks passed');
