'use strict';
const assert=require('node:assert/strict'),m=require('./personal_progressive_fitness_nutrition_v83.js');
const valid={label:'Upper body',type:'Gym',minutes:90,intensity:'Moderate',detail:'Bench press and rows'};
assert.equal(m.validateWorkout(valid).ok,true);
assert.equal(m.validateWorkout({...valid,label:' '}).ok,false);
assert.equal(m.validateWorkout({...valid,type:'Unknown'}).ok,false);
assert.equal(m.validateWorkout({...valid,minutes:-1}).ok,false);
assert.equal(m.validateWorkout({...valid,minutes:1441}).ok,false);
assert.equal(m.validateWorkout({...valid,minutes:1.5}).ok,false);
assert.equal(m.validateWorkout({...valid,intensity:'Extreme'}).ok,false);
assert.equal(m.validateWorkout({...valid,detail:'x'.repeat(501)}).ok,false);
assert.equal(m.validateWorkout({...valid,minutes:''}).preset.minutes,null);
const add=m.addPreset([],valid,'id1');
assert.equal(add.ok,true);
assert.equal(add.list.length,1);
assert.equal(add.list[0].id,'id1');
assert.equal(m.addPreset(add.list,{...valid,label:'upper BODY'},'id2').ok,false);
assert.equal(m.addPreset(add.list,{...valid,label:'Leg day'},'id2').ok,true);
assert.equal(m.cleanPresets([{...valid,id:'a'},{...valid,id:42},{...valid,id:'c',type:'bad'}]).length,1);
assert.equal(m.addPreset(Array.from({length:30},(_,i)=>({...valid,label:'preset'+i,id:'id'+i})),{...valid,label:'New'},'id31').ok,false);
assert.equal(m.favoriteMeals([{id:'a',name:'Rice'},{id:'b',name:''},{name:'Fish'},{id:'c',name:'Chicken'}]).length,2);
assert.deepEqual(m.summary({workouts:[{id:'a'},{id:'b',source:'assumed-demo'}],meals:[{id:'c'},{id:'d',seedBatch:'x'}],mealTemplates:[{id:'x',name:'Oats'}]}),{workouts:1,meals:1,templates:1});
assert.equal(m.TYPES.includes('Gym'),true);
assert.equal(m.KEY,'lifeos.personal.fitness-presets.v83');
console.log('V83: 20 personalization assertions passed');
