'use strict';
const assert=require('node:assert/strict'),v=require('./personal_background_tracking_v72.js');
const now=10_000_000,h=3600000;
const running={id:'running',name:'Study',status:'running',segments:[{start:now-3*h,end:null}]};
const paused={id:'paused',name:'Break',status:'paused',segments:[{start:now-4*h,end:now-3*h},{start:now-2*h,end:now-h}]};
const finished={id:'finished',name:'Done',status:'finished',segments:[{start:now-4*h,end:now-3*h}]};
const workspace={version:1,sessions:[running,paused,finished],schedule:[],events:[]};
assert.equal(v.elapsed(running,now),3*h,'running duration derives from wall time');
assert.equal(v.elapsed(running,now+2*h),5*h,'time advances after background suspension');
assert.equal(v.elapsed(paused,now),2*h,'paused time does not advance');
assert.equal(v.elapsed(paused,now+3*h),2*h,'paused timer remains stopped after long lock');
assert.equal(v.elapsed(finished,now+3*h),h,'finished timer remains constant');
assert.equal(v.inspect(workspace,now).active,2,'finished activity not displayed among active');
assert.equal(v.inspect(workspace,now).running,1);
assert.equal(v.inspect(workspace,now).paused,1);
assert.equal(v.inspect(workspace,now).warnings,0);
assert.equal(v.inspect({sessions:[{...running,segments:[{start:now+h,end:null}]}]},now).warnings,1,'future start flagged');
assert.equal(v.inspect({sessions:[{...running,segments:[{start:now-h,end:now},{start:now-h,end:null}]}]},now).warnings,0,'past closed segment + current open segment allowed');
assert.equal(v.inspect({sessions:[{...paused,segments:[{start:now-h,end:null}]}]},now).warnings,1,'paused timer cannot hold open segment');
const saved={format:1,workspace};
assert.equal(v.compareCheckpoint(workspace,JSON.stringify(saved),()=>saved).ok,true);
assert.equal(v.compareCheckpoint(workspace,'corrupt',()=>saved).ok,false);
assert.equal(v.compareCheckpoint(workspace,JSON.stringify({format:2}),()=>saved).ok,true);
assert.equal(v.compareCheckpoint(workspace,JSON.stringify({format:2})).ok,false);
assert.equal(v.compareCheckpoint({...workspace,sessions:[]},JSON.stringify(saved)).ok,false);
console.log('V72: 17 background timer and checkpoint regression assertions passed');
