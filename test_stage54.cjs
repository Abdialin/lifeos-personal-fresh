'use strict';
const assert=require('node:assert/strict');
const t=require('./personal_activity_timeline_v54.js');
const day='2026-11-14',a=new Date(day+'T00:00:00').getTime(),h=3600000;
assert.equal(t.bounds('2026-02-30'),null);
assert.deepEqual(t.merge([[0,100],[30,80],[100,200]]),[[0,200]]);
assert.deepEqual(t.gaps([[0,10]],0,100,45),[[10,100]]);
const w={sessions:[{id:'a',name:'Study',status:'finished',segments:[{start:a+8*h,end:a+10*h}]},{id:'b',name:'Reading',status:'finished',segments:[{start:a+9*h,end:a+11*h}],precision:'retrospective-approximate'},{id:'c',name:'Sample',status:'finished',segments:[{start:a+12*h,end:a+13*h}],source:'development-starter'}],schedule:[{id:'p',name:'Planned',startAt:a+8*h,endAt:a+11*h,status:'planned'}]};
const result=t.build(w,day,a+14*h);
assert.equal(result.stats.observedMs,3*h,'overlapping tracked sessions must not double count');
assert.equal(result.stats.plannedMs,3*h);
assert.equal(result.stats.exampleCount,1);
assert.equal(result.overlaps.length,1);
assert.equal(result.gaps.length,2);
const future=t.build({schedule:[{id:'p',name:'Future',startAt:a+15*h,endAt:a+16*h}]},day,a+10*h);
assert.equal(future.cutoff,a+10*h);
assert.equal(future.stats.observedMs,0);
assert.equal(future.gaps[0][1],a+10*h);
console.log('V54 focused timeline checks passed');
