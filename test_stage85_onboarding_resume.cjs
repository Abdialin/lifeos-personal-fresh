'use strict';
const assert=require('node:assert/strict');
const v=require('./personal_onboarding_resume_v85.js');
const r=require('./personal_guided_onboarding_v81.js');
const storage={data:new Map(),getItem(k){return this.data.get(k)||null},setItem(k,v){this.data.set(k,String(v))},removeItem(k){this.data.delete(k)}};
const draft={routines:[{name:'Gym',days:[1,3],time:'18:00',minutes:90}],habits:[{title:'Read Quran',everyDays:1}],tasks:[{name:'Buy groceries'}]};
assert.equal(v.read(storage).ok,false);
assert.equal(v.valid({version:1,step:3,draft}),true);
assert.equal(v.save(storage,draft,3,1000).ok,true);
const saved=v.read(storage);
assert.equal(saved.ok,true);
assert.equal(saved.step,3);
assert.equal(saved.draft.routines[0].name,'Gym');
assert.equal(saved.updatedAt,1000);
draft.routines[0].name='Changed afterwards';
assert.equal(v.read(storage).draft.routines[0].name,'Gym','serialized draft must be immutable');
assert.equal(v.save(storage,{...draft,routines:[{name:'X',days:[7],time:'18:00',minutes:60}]},1).ok,false);
assert.equal(v.save(storage,{routines:[],habits:[],tasks:[]},4).ok,false);
assert.equal(v.save(storage,{routines:[],habits:[],tasks:[]},0).ok,true);
assert.equal(v.clear(storage),true);
assert.equal(v.read(storage).ok,false);
storage.setItem(v.KEY,'invalid');
assert.equal(v.read(storage).ok,false);
const now=new Date(2026,10,16,8).getTime();
const initial=r.prepare({routines:[{name:'Gym',days:[1,3],time:'18:00',minutes:90}],habits:[],tasks:[]},{schedule:[]},now);
const same=r.prepare({routines:[{name:'Gym',days:[1,3],time:'18:00',minutes:90}],habits:[],tasks:[]},{schedule:[]},now);
assert.equal(v.sameReview(initial,same),true);
const modified={...same,plans:[{...same.plans[0],name:'Changed'},...same.plans.slice(1)]};
assert.equal(v.sameReview(initial,modified),false,'same count but changed plan must fail');
const overlapped=r.prepare({routines:[{name:'Gym',days:[1,3],time:'18:00',minutes:90}],habits:[],tasks:[]},{schedule:[{id:'x',startAt:initial.plans[0].startAt,endAt:initial.plans[0].endAt,name:'Meeting',status:'planned'}]},now);
