assert.equal(v.sameReview(null,initial),false);
const old={...initial,habits:[{title:'Quran',everyDays:1}]};
assert.equal(v.sameReview(initial,old),false);
assert.equal(v.sameReview(initial,{...initial,tasks:[{name:'Buy groceries'}]}),false);
assert.equal(v.sameReview(initial,{...initial,blocked:[{name:'Gym',reason:'overlap',startAt:123,endAt:124}]}),false);
assert.equal(v.valid({version:2,step:1,draft}),false);
