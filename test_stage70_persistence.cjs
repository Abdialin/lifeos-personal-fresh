'use strict';
const assert=require('node:assert/strict');
const {verify,compareRecords,same}=require('./personal_persistence_validator_v70.js');
const live={version:1,sessions:[{id:'s1',name:'Activity',status:'finished',startAt:100,endAt:200,segments:[{start:100,end:200}]}],schedule:[{id:'p1',name:'Plan',startAt:300,endAt:400,status:'planned'}],events:[{id:'e1',sessionId:'s1',type:'START',time:100}]};
const encoded=JSON.stringify({format:1,workspace:live,journal:[]});
assert.equal(verify(encoded,live).ok,true);
assert.equal(verify(JSON.stringify({format:2,packed:true}),live,()=>({workspace:live})).ok,true);
assert.equal(verify(JSON.stringify({format:2,packed:true}),live).ok,false);
assert.equal(verify('invalid',live).ok,false);
assert.equal(verify('',live).ok,false);
assert.equal(compareRecords({...live,sessions:[{...live.sessions[0],status:'running'}]},live).ok,false);
assert.equal(compareRecords({...live,schedule:[{...live.schedule[0],startAt:301}]},live).ok,false);
assert.equal(compareRecords({...live,events:[{...live.events[0],type:'STOP'}]},live).ok,false);
assert.equal(compareRecords({...live,sessions:[]},live).ok,false,'saved-only session detected');
assert.equal(compareRecords({...live,schedule:[]},live).ok,false,'saved-only plan detected');
assert.equal(compareRecords({...live,events:[]},live).ok,false,'saved-only event detected');
assert.equal(compareRecords({...live,sessions:[...live.sessions,live.sessions[0]]},live).ok,false,'duplicate identifier detected');
assert.equal(same({a:1,b:2},{b:2,a:1}),true,'key order irrelevant');
assert.ok(verify(encoded,live).counts.sessions.saved===1);
console.log('V70 strict checkpoint verification: 14/14 assertions passed');
