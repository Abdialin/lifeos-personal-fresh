const assert=require('node:assert/strict'),fs=require('node:fs');
const api=require('./personal_timer_history_v248.js'),H=3600000,at=8*H;
const s={id:'test',name:'Study',status:'running',segments:[{start:1*H,end:3*H},{start:3*H+2*60000,end:4*H},{start:6*H,end:null}]};
const r=api.analyze(s,at);
assert.equal(r.activeMs,5*H-2*60000);
assert.equal(r.pauses.length,1);
assert.equal(r.pauses[0].ms,2*H);
assert.equal(r.elapsedWallMs,7*H);
assert.equal(r.status,'running');
assert.equal(api.analyze({...s,status:'paused',segments:[{start:H,end:2*H}]},at).pauseNowSince,2*H);
assert.equal(api.analyze({...s,status:'finished'},at),null);
assert.equal(api.analyze({...s,status:'running',segments:[{start:H,end:2*H},{start:2*H+3*60000,end:3*H}]},at).pauses.length,0);
assert.equal(s.segments[2].end,null,'must not modify source activity');
const src=fs.readFileSync('personal_timer_history_v248.js','utf8'),html=fs.readFileSync('index.html','utf8'),server=fs.readFileSync('server.py','utf8');
assert.match(src,/LifeOSReviewTimer\(report\.id\)/);
assert.doesNotMatch(src,/requestState\('PUT'|atomicCommit\(|localStorage\.setItem\(|\.segments\.push\(/);
assert.match(html,/personal_timer_history_v248\.js\?v=20261119-v248/);
assert.match(server,/'personal_timer_history_v248\.js'/);
console.log('PASS V248 paused gap threshold, open timer durations, read-only timeline, review navigation');
