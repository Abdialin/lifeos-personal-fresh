'use strict';
const assert=require('node:assert/strict');
const model=require('./personal_weekly_recommendations_v61.js');
const start=new Date('2026-11-15T00:00:00').getTime(),hour=3600000;
const days=Array.from({length:7},(_,i)=>({date:'2026-11-'+String(15+i),start:start+i*24*hour,plannedMs:i===0?9*hour:i===1?3*hour:0,overlaps:i===0?[{first:'Study',second:'Work'}]:[],shortBreaks:i===0?[{from:'Study',to:'Gym',minutes:10}]:[],highLoad:i===0,predictions:[]}));
const original=JSON.stringify(days),result=model.propose({days,summary:{evidence:{confidence:'insufficient'}}});
assert.equal(result.error,null);
assert.ok(result.suggestions.find(x=>x.id==='conflict:'+days[0].date));
const heavy=result.suggestions.find(x=>x.id==='load:'+days[0].date);
assert.ok(heavy&&heavy.candidateDates.length===2);
assert.equal(heavy.candidateDates[0].plannedHours,0);
assert.ok(result.suggestions.find(x=>x.id==='break:'+days[0].date));
assert.ok(result.suggestions.find(x=>x.id==='evidence'));
assert.equal(result.suggestions[0].priority,'high');
assert.ok(result.suggestions.every(x=>x.reviewOnly));
assert.equal(JSON.stringify(days),original);
assert.ok(model.propose(null).error);
const stable=model.propose({days:days.map(x=>({...x,plannedMs:0,highLoad:false,overlaps:[],shortBreaks:[]})),summary:{evidence:{confidence:'reviewable'}}});
assert.equal(stable.suggestions.length,1);
assert.equal(stable.suggestions[0].id,'stable');
console.log('V61 weekly recommendations checks passed');
