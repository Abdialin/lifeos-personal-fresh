const assert=require('node:assert/strict');
const fs=require('node:fs');
const gradle=fs.readFileSync('android-companion/app/build.gradle.kts','utf8');
const workflow=fs.readFileSync('.github/workflows/personal-android-build.yml','utf8');
const manifest=fs.readFileSync('android-companion/app/src/main/AndroidManifest.xml','utf8');
assert.match(gradle,/applicationId = "com\.lifeos\.companion\.beta"/,'Independent beta package required');
assert.match(gradle,/applicationIdSuffix = "\.dev"/,'Disposable dev must not clash with persistent beta');
assert.match(gradle,/versionCode = 9/);
assert.match(gradle,/stableSigningReady/);
assert.match(gradle,/create\("privateBeta"\)/);
assert.match(gradle,/signingConfig = signingConfigs\.getByName\("privateBeta"\)/);
assert.match(manifest,/android:label="LifeOS Beta"/);
assert.match(workflow,/lifeos-android-v238-disposable-dev-test-only/);
assert.match(workflow,/lifeos-android-v238-signed-beta/);
assert.match(workflow,/package: name='com\.lifeos\.companion\.beta\.dev'/);
assert.match(workflow,/package: name='com\.lifeos\.companion\.beta'/);
assert.match(workflow,/secrets\.LIFEOS_BETA_KEYSTORE_BASE64/);
assert.match(workflow,/if: steps\.signing\.outputs\.ready == 'true'/);
assert.match(workflow,/apksigner" verify --print-certs/);
assert.doesNotMatch(gradle,/\.keystore\.jks|\.p12"\s*\/\//,'No committed signing key paths');
console.log('V238 signing gates, independent package IDs, stable signature verification PASS');
