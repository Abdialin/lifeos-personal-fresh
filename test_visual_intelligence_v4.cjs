const assert=require('node:assert/strict');
const fs=require('node:fs');
const html=fs.readFileSync('index.html','utf8');
const visual=fs.readFileSync('personal_visual_intelligence_v4.js','utf8');
const analytics=require('./lifeos_unified_analytics.js');
assert.doesNotThrow(()=>new Function(visual));
assert.match(html,/<script src="personal_visual_intelligence_v4\.js" defer><\/script>/);
assert.match(html,/lifeosReadOnlyWorkspace=\(\)=>JSON\.parse\(JSON\.stringify\(\{sessions:data\.sessions\|\|\[\],schedule:data\.schedule\|\|\[\],idealRoutines:data\.idealRoutines\|\|\[\]\}\)\)/);
for(const id of ['v4Today','v4Insights','v4Plan'])assert.ok(visual.includes(id));
assert.ok(visual.includes('section.hidden=true'),'Visual panels should start hidden');
assert.ok(!/\bpersist\s*\(|\blocalStorage\.setItem\s*\(/.test(visual),'Visualization must not write storage');
const now=new Date(2026,10,11,12).getTime(),hour=3600000;
const workspace={sessions:[{id:'a',name:'Work',status:'finished',segments:[{start:now-2*hour,end:now}]},{id:'b',name:'Study',status:'running',segments:[{start:now-hour,end:null}]}],schedule:[{name:'Gym',startAt:now+hour,endAt:now+2*hour}]};
const day=analytics.daily(workspace,{year:2026,month:11,day:11,now});
assert.equal(day.summedRecordedMs,3*hour);
assert.equal(day.uniqueRecordedMs,2*hour);
assert.equal(day.overlapRecordedMs,hour);
assert.equal(day.summedPlannedMs,hour);
assert.match(visual,/span=en-st/,'Timeline must use actual local-day length (23, 24 or 25 hours)');
assert.match(visual,/Math\.min\(100-left/,'Timeline bars must not overflow their day');
assert.match(visual,/visibilitychange/,'Visuals should refresh when returning to the tab');
assert.match(visual,/month\.setDate\(1\);month\.setMonth/,'Month navigation must avoid end-of-month rollover');
for(const title of ['My Reality', 'My Predicted Week', 'My Ideal Schedule'])assert.ok(visual.includes(title),'Missing planning view: '+title);
assert.match(visual,/planningComparison\(ws,now\)\+chartCard/,'Three-view summary must be rendered with the calendar');
assert.match(visual,/Missing logs are unknown time, not free time/,'Predictions must not assume unlogged time is available');
assert.match(visual,/planner\.dayTypePatterns\(ws\.sessions\|\|\[\],now\)/,'Predicted Week should use historical day-type evidence');
assert.match(visual,/Observed weekday frequency, not a forecast/,'Observed patterns must not be mislabelled as forecasts');
assert.match(visual,/overlapping plan pair\(s\) this week/,'Weekly plan conflicts must be explained');
assert.match(visual,/Recorded during planned time/,'Plan-reality alignment must be visible');
assert.match(visual,/Overlapping planned hours/,'Plan overlaps must be visible');
assert.match(visual,/planner\.build\(\{routines:ws\.idealRoutines\|\|\[\]/,'Ideal proposals should use the existing approval-only planner');
assert.match(visual,/All require your approval in Plan/,'No visual proposal should imply automatic approval');
assert.match(visual,/data-v4-review-ideal/,'Ideal cards must provide a review action');
assert.match(visual,/button\.click\(\)/,'Ideal review must delegate to existing approval workflow');
assert.match(html,/const fresh=window\.LifeOSIdealPlanning\.review\(\[proposal\],data\.schedule\|\|\[\]\)\[0\]/,'Approval must recalculate conflicts against current schedule');
assert.match(html,/LifeOSPersonalPlanner\.approve\(/,'Approval must use guarded planner method');
assert.match(visual,/details\.open=true/,'Visual review must reveal collapsed approval controls');
assert.match(html,/sessionIntervals\(s,now\(\)\)\.some/,'Approval must check actual recorded session intervals');
assert.match(html,/This proposal overlaps.*tracked activity session/,'Recorded-session conflicts must block approval');
console.log('V4 visual integration PASS');
