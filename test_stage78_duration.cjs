'use strict';
const assert=require('node:assert/strict');
const g=require('./personal_duration_guard_v78.js');
const MIN=60000,at=Date.UTC(2026,10,14,23,30);
const prayer={id:'p',name:'Dhuhr prayer',status:'running',startAt:at-40*MIN,segments:[{start:at-40*MIN,end:null}]};
const quran={id:'q',name:'Quran memorization',status:'running',startAt:at-90*MIN,segments:[{start:at-90*MIN,end:null}]};
assert.equal(g.suggestion('Fajr prayer'),30);
assert.equal(g.suggestion('Dhuhr prayer'),30);
assert.equal(g.suggestion('Quran memorization'),60);
assert.equal(g.suggestion('Gym session'),90);
assert.equal(g.suggestion('Security shift'),480);
assert.equal(g.valid(prayer),null);
assert.equal(g.inspect(prayer,at).configured,false);
assert.equal(g.configure(prayer,30,'auto',at).ok,false,'never auto-shorten historical running session');
assert.equal(g.configure(prayer,45,'auto',at).ok,true);
assert.equal(g.configure(prayer,30,'warn',at).ok,true,'reminder may be overdue');
assert.equal(g.configure(prayer,0,'warn',at).ok,false);
assert.equal(g.configure(prayer,1500,'auto',at).ok,false);
assert.equal(g.configure(prayer,30,'magic',at).ok,false);
const auto={...prayer,durationGuardV78:{targetMinutes:45,mode:'auto'}};
assert.equal(g.shouldAutoFinish(auto,at),false);
assert.equal(g.shouldAutoFinish(auto,at+5*MIN),true);
assert.equal(g.inspect(auto,at+15*MIN).dueAt,at+5*MIN,'late wake-up cuts at configured time');
assert.equal(g.boundary(auto,45*MIN,at+10*MIN),at+5*MIN);
const paused={id:'paused',name:'Gym',status:'running',startAt:at-50*MIN,segments:[{start:at-50*MIN,end:at-30*MIN},{start:at-15*MIN,end:null}],durationGuardV78:{targetMinutes:40,mode:'auto'}};
assert.equal(g.elapsed(paused,at),35*MIN);
assert.equal(g.shouldAutoFinish(paused,at),false);
assert.equal(g.shouldAutoFinish(paused,at+5*MIN),true);
assert.equal(g.boundary(paused,40*MIN,at+6*MIN),at+5*MIN,'paused duration excluded');
const warn={...prayer,durationGuardV78:{targetMinutes:30,mode:'warn'}};
assert.equal(g.inspect(warn,at).overdue,true);
assert.equal(g.shouldAutoFinish(warn,at),false);
assert.equal(g.extend(warn,15,at).settings.targetMinutes,45);
assert.equal(g.extend(auto,5,at).ok,true);
assert.equal(g.extend(auto,4,at).ok,false);
assert.equal(g.extend(auto,241,at).ok,false);
assert.equal(g.extend({...prayer,status:'finished',durationGuardV78:{targetMinutes:30,mode:'warn'}},15,at).ok,false);
assert.equal(g.shouldAutoFinish({...prayer,status:'paused',durationGuardV78:{targetMinutes:30,mode:'auto'}},at),false);
assert.equal(g.inspect(quran,at).suggestionMinutes,60);
console.log('V78 duration guard: 30 behavioral assertions passed.');
