const assert=require('node:assert/strict');
const c=require('./personal_continuity.js');const t=Date.UTC(2026,10,8,12);const M=60000;
assert.equal(c.inspectResume({sessions:[]},t).hasUnresolved,false);
const s={id:'s1',status:'running',segments:[{start:t-300*M,end:null}]};
assert.equal(c.inspectResume({sessions:[s]},t).issues[0].kind,'stale-running-session');
assert.equal(s.status,'running');
assert.equal(c.inspectResume({sessions:[s]},t,400).issues.length,0);
assert.equal(c.inspectResume({sessions:[{id:'bad',status:'running',segments:[]}]},t).issues[0].action,'manual-review');
const p={id:'p1',name:'Study',status:'planned',reminder:true,startAt:t+5*M,endAt:t+65*M};
const upcoming=c.notificationCandidates([p],t);assert.equal(upcoming[0].phase,'upcoming');
assert.equal(c.notificationCandidates([p],t-20*M).length,0);
assert.equal(c.notificationCandidates([{...p,reminderReview:{state:'dismissed'}}],t).length,0);
assert.equal(c.notificationCandidates([{...p,reminderReview:{snoozedUntil:t+M}}],t).length,0);
assert.equal(c.notificationCandidates([p],t+70*M)[0].phase,'missed');
assert.equal(c.unseenNotifications(upcoming,[upcoming[0].key]).length,0);
assert.equal(c.markDelivered([],upcoming[0].key).length,1);
assert.equal(c.markDelivered([upcoming[0].key],upcoming[0].key).length,1);
assert.throws(()=>c.inspectResume({sessions:[]},NaN));
console.log('Personal continuity checks passed');
