'use strict';
const assert=require('node:assert/strict');
const v=require('./personal_guided_onboarding_v81.js');
const now=new Date(2026,10,15,7,0,0,0).getTime();
const routine={name:'Gym',days:[0,2,4],time:'18:00',minutes:90};
assert.equal(v.times('Gym',[0,2], '18:00',90).days.length,2);
assert.equal(v.times('Gym',[], '18:00',90),null);
assert.equal(v.times('Gym',[7], '18:00',90),null);
assert.equal(v.times('Gym',[0], '99:00',90),null);
assert.equal(v.times('Gym',[0], '18:00',0),null);
assert.equal(v.times('Gym',[0], '18:00',721),null);
const plans=v.nextWeek([routine],now);
assert.equal(plans.length,3);
assert.equal(plans[0].name,'Gym');
assert.equal(plans[0].status,'planned');
assert.equal(plans[0].sessionId,undefined,'never makes recorded sessions');
assert.equal(plans[0].endAt-plans[0].startAt,90*60000);
assert.equal(plans[0].source,'onboarding-v81');
assert.equal(v.conflicts(plans[0],[]).length,0);
assert.equal(v.conflicts(plans[0],[{startAt:plans[0].startAt+60000,endAt:plans[0].endAt+60000,status:'planned'}]).length,1);
assert.equal(v.conflicts(plans[0],[{startAt:plans[0].startAt+60000,endAt:plans[0].endAt+60000,status:'skipped'}]).length,0);
let p=v.prepare({routines:[routine],habits:[{title:'Read Quran',everyDays:1}],tasks:[{name:'Buy groceries'}]},{schedule:[],todos:[],habitDefinitions:[]},now);
assert.equal(p.ok,true);
assert.equal(p.plans.length,3);
assert.equal(p.habits.length,1);
assert.equal(p.tasks.length,1);
assert.equal(p.blocked.length,0);
assert.equal(p.habits[0].targetMode,'completion');
assert.equal(p.tasks[0].timingType,'anytime');
assert.equal(p.tasks[0].done,false);
p=v.prepare({routines:[routine],habits:[{title:'Read Quran',everyDays:1}],tasks:[{name:'Buy groceries'}]},{schedule:[{...plans[0],id:'existing'}],todos:[{name:'Buy groceries',done:false}],habitDefinitions:[{title:'Read Quran'}]},now);
assert.equal(p.plans.length,2);
assert.equal(p.blocked.length,1);
assert.equal(p.habits.length,0);
assert.equal(p.tasks.length,0);
assert.equal(v.prepare({routines:[],habits:[{title:'x',everyDays:0}],tasks:[]},{schedule:[]},now).ok,false);
assert.equal(v.prepare({routines:[],habits:[],tasks:[{name:''}]},{schedule:[]},now).ok,false);
assert.equal(v.prepare({routines:[],habits:[],tasks:[]},{schedule:[]},now).ok,true);
console.log('V81 onboarding: 29 guided setup assertions passed');
