'use strict';
const assert=require('node:assert/strict');
const engine=require('./personal_background_tracking_v72.js');
const subject=require('./personal_device_tracking_test_v73.js');
const START=10_000_000,MIN=60000;
const running={id:'r',name:'Reading',status:'running',startAt:START-5*MIN,segments:[{start:START-5*MIN,end:null}]};
const paused={id:'p',name:'Rest',status:'paused',startAt:START-10*MIN,segments:[{start:START-10*MIN,end:START-7*MIN}]};
const workspace={version:1,sessions:[running,paused],schedule:[],events:[]};
const r=subject.capture(workspace,'r',START,engine);
assert.equal(r.ok,true);
assert.equal(r.baseline.elapsedMs,5*MIN);
assert.equal(r.baseline.id,'r');
assert.equal(subject.evaluate(r.baseline,workspace,START+2*MIN,engine,{ok:true}).state,'pass');
assert.equal(subject.evaluate(r.baseline,workspace,START+2*MIN,engine,{ok:false}).state,'fail');
assert.equal(subject.evaluate(r.baseline,workspace,START+10*1000,engine,{ok:true}).state,'review');
assert.equal(subject.evaluate(r.baseline,workspace,START-1,engine,{ok:true}).state,'review');
assert.equal(subject.evaluate(r.baseline,{...workspace,sessions:[]},START+MIN,engine,{ok:true}).state,'fail');
assert.equal(subject.evaluate(r.baseline,{...workspace,sessions:[{...running,startAt:START-4*MIN},paused]},START+MIN,engine,{ok:true}).state,'fail');
assert.equal(subject.evaluate(r.baseline,{...workspace,sessions:[{...running,status:'paused',segments:[{start:START-5*MIN,end:START}]},paused]},START+MIN,engine,{ok:true}).state,'review');
assert.equal(subject.evaluate(r.baseline,{...workspace,sessions:[{...running,segments:[{start:START-4*MIN,end:null}]},paused]},START+MIN,engine,{ok:true}).state,'review');
const p=subject.capture(workspace,'p',START,engine);
assert.equal(p.ok,true);
assert.equal(subject.evaluate(p.baseline,workspace,START+2*MIN,engine,{ok:true}).state,'pass');
assert.equal(subject.evaluate(p.baseline,{...workspace,sessions:[running,{...paused,segments:[{start:START-10*MIN,end:START-6*MIN}]}]},START+2*MIN,engine,{ok:true}).state,'fail');
assert.equal(subject.capture(workspace,'missing',START,engine).ok,false);
assert.equal(subject.evaluate(null,workspace,START+MIN,engine,{ok:true}).state,'not-started');
assert.equal(subject.evaluate(r.baseline,{...workspace,sessions:[{...running,segments:[{start:START+MIN,end:null}]},paused]},START+2*MIN,engine,{ok:true}).state,'fail');
console.log('V73 device lock/resume simulation: 17/17 assertions passed.');
